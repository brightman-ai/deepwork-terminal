/**
 * tabChrome — 标签栏上那些**两个壳必须长一样**的取值。
 *
 * standalone 的 `CliTabBar.vue` 与 pro 的 `TopTabBar.vue` 是两个 presentational 组件（刻意的：
 * 它们嵌在完全不同的外壳里），但用户看到的是同一个产品。凡是"行为语义"级的取值就必须只有一份，
 * 否则两边各自演化，最后就是同一个功能在两个壳里表现不同 —— 这个仓吃过很多次亏。
 */

/**
 * 关闭 ✕ 的不透明度。**关键在于 idle 不是 0**。
 *
 * 曾经 standalone 把非当前标签的 ✕ 设为 `opacity: 0`，靠 `:hover` 才揭示。桌面上看不出问题，
 * 手机上是实打实的缺陷：iOS 对"一碰就改变内容"的元素会把**第一次点击当成 hover 吃掉**，
 * 于是切标签必须点两下（用户实测原话："单击终端1 终端2 不会切换，要点2次"）。
 *
 * 修法不是给触摸设备加一条特判 —— 那是把一个条件变成两个条件。直接删掉这个条件：✕ 常驻，
 * hover 只是加深。pro 一直就是这么做的，所以这也是把两壳收敛到同一个行为，而不是引入第三种。
 *
 * 顺带也更符合《设计心理学》：**看不见的可供性不算可供性**。要关一个标签，得先把鼠标移上去
 * 才知道能关，本来就是多余的一步。
 */
export const TAB_CLOSE_OPACITY = {
  /** 常态：看得见，但不与标签名争注意力。 */
  idle: '0.55',
  /** 指针悬在 ✕ 上：这是可点的。 */
  hover: '1',
} as const
